"""Generates the Graphic Design Studio System Console installer from the JSON definitions.

Usage: python tools/erp/design_studio/build_installer.py [--check]
--check exits 1 when the generated installer is missing or out of date.
"""
import json
import pathlib
import pprint
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
GDS = ROOT / "10. Communication & Productivity" / "Graphic Design Studio"
SRC = GDS / "doctypes"
OUT = GDS / "install" / "install_design_studio.py"

HEADER = '''# Graphic Design Studio: creates the Design DocTypes, the Design Manager role, the Employee and
# Designation custom fields, the six brands and the default settings. Paste into ERP > System Console
# and press Execute (as Administrator or a System Manager). Anything that already exists is left as it is,
# so running it twice is safe. Setup: 10. Communication & Productivity/Graphic Design Studio/README.md
# Generated by tools/erp/design_studio/build_installer.py from doctypes/*.json. Edit those, not this copy.
'''

BODY = '''
LINKING = ["Link", "Table", "Table MultiSelect"]
created = []


def target_ready(field, owner):
    if field["fieldtype"] not in LINKING:
        return True
    return field["options"] == owner or bool(frappe.db.exists("DocType", field["options"]))


for role in ROLES:
    if not frappe.db.exists("Role", role):
        frappe.get_doc({"doctype": "Role", "role_name": role, "desk_access": 1}).insert()
        created.append("Role " + role)

# Frappe refuses a Link to a DocType that does not exist yet, and these DocTypes link in a loop
# (brand -> logo asset -> asset brand -> brand). Insert whatever is ready; when nothing is, insert the
# first waiting DocType without its unresolved links and add those fields once their targets exist.
pending = [d for d in DEFINITIONS if not frappe.db.exists("DocType", d["name"])]
deferred = []
while pending:
    waiting = []
    for definition in pending:
        if all(target_ready(f, definition["name"]) for f in definition["fields"]):
            frappe.get_doc(definition).insert()
            created.append(definition["name"])
        else:
            waiting.append(definition)
    if len(waiting) == len(pending):
        first = waiting[0]
        keep = [f for f in first["fields"] if target_ready(f, first["name"])]
        later = [f for f in first["fields"] if not target_ready(f, first["name"])]
        partial = dict(first)
        partial["fields"] = keep
        frappe.get_doc(partial).insert()
        created.append(first["name"] + " (links added after)")
        deferred.append([first["name"], later])
        waiting = waiting[1:]
    pending = waiting

for name, fields in deferred:
    doc = frappe.get_doc("DocType", name)
    for field in fields:
        doc.append("fields", field)
    doc.save()

for field in CUSTOM_FIELDS:
    if not frappe.db.exists("Custom Field", {"dt": field["dt"], "fieldname": field["fieldname"]}):
        row = dict(field)
        row["doctype"] = "Custom Field"
        frappe.get_doc(row).insert()
        created.append("Custom Field " + field["dt"] + "." + field["fieldname"])

for brand in BRANDS:
    if not frappe.db.exists("Design Brand", brand["brand_name"]):
        row = dict(brand)
        row["doctype"] = "Design Brand"
        frappe.get_doc(row).insert()
        created.append("Brand " + brand["brand_name"])

settings = frappe.get_doc("Design Studio Settings")
changed = False
for key in SETTINGS:
    if not frappe.db.get_single_value("Design Studio Settings", key):
        settings.set(key, SETTINGS[key])
        changed = True
if changed:
    settings.save()
    created.append("Design Studio Settings defaults")

frappe.db.commit()
frappe.msgprint("Created: " + (", ".join(created) or "nothing, everything already exists"))
'''


def load():
    defs, fields, seed = [], [], {}
    for path in sorted(SRC.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if path.name == "custom_fields.json":
            fields = data
        elif path.name == "seed.json":
            seed = data
        else:
            defs.append(data)
    # child tables first keeps the number of deferred links small
    defs.sort(key=lambda d: (0 if d.get("istable") else 1, d["name"]))
    return defs, fields, seed


def render():
    defs, fields, seed = load()
    fmt = lambda v: pprint.pformat(v, width=110, sort_dicts=False)
    parts = [HEADER, "\nROLES = " + fmt(seed["roles"]), "\nDEFINITIONS = " + fmt(defs), "\nCUSTOM_FIELDS = " + fmt(fields),
             "\nBRANDS = " + fmt(seed["brands"]), "\nSETTINGS = " + fmt(seed["settings"]), "\n", BODY]
    return "".join(parts)


def main():
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("stale: " + str(OUT.relative_to(ROOT)) + " (run build_installer.py)")
            sys.exit(1)
        print("installer up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote " + str(OUT.relative_to(ROOT)))


if __name__ == "__main__":
    main()
