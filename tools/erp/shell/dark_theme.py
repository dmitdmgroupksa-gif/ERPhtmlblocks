"""Generate a Desk-following dark theme for dashboards that have none.

For each dashboard listed under "dark" in shell_map.json:
  1. Reads its stylesheet (minus generated blocks), and for every rule that sets a colour (background, border, text, fill,
     stroke, gradients, colour tokens) writes a dark equivalent scoped to
       :host([data-dms-theme="dark"]) <selector>   (Custom HTML Block rendered in a shadow root)
       html[data-theme="dark"] <selector>          (document fallback)
     Light surfaces become dark surfaces, dark text becomes light text; hue is kept, so status colours stay recognisable.
     Brand/accent colours and anything already dark are left alone.
  2. Appends a tiny script to dashboard.js that mirrors Desk's <html data-theme> onto the block host.
Re-running replaces both generated blocks; --remove deletes them; --check reports stale ones.
"""
import colorsys, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
CFG = json.loads((pathlib.Path(__file__).parent / 'shell_map.json').read_text(encoding='utf-8'))
BEGIN = '/* ==== DM dark theme v1 · generated by tools/erp/shell/dark_theme.py · do not edit by hand ==== */'
END = '/* ==== end DM dark theme v1 ==== */'
JS_BEGIN = '/* ==== DM theme sync v1 · generated by tools/erp/shell/dark_theme.py ==== */'
JS_END = '/* ==== end DM theme sync v1 ==== */'
SYNC = (JS_BEGIN + '\n;(function () {\n'
        "  var r = typeof root_element !== 'undefined' ? root_element : null, h = r && r.host;\n"
        '  if (!h || h.__dmsTheme) return; h.__dmsTheme = 1;\n'
        "  var s = function () { h.setAttribute('data-dms-theme', document.documentElement.getAttribute('data-theme') === 'dark' ? 'dark' : 'light'); };\n"
        "  s(); new MutationObserver(s).observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });\n"
        '})();\n' + JS_END + '\n')
SCOPES = [':host([data-dms-theme="dark"])', 'html[data-theme="dark"]']
NAMED = {'white': (255, 255, 255, 1), 'black': (0, 0, 0, 1), '#fff': None}
BG_TOKEN = re.compile(r'(bg|background|paper|surface|card|panel|line|border|soft|tint|light|track|row|hover|stripe|chip|well|field|input|base|canvas|page|sheet|shade|zebra|grey|gray|neutral|muted-bg|subtle)', re.I)
TEXT_TOKEN = re.compile(r'(ink|text|fg|title|head|muted|sub|label|body|copy|strong|dim|faint|caption|meta)', re.I)
COLOR_RE = re.compile(r'#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b|rgba?\([^)]*\)|\b(?:white|black)\b')


def parse_color(s):
    s = s.strip().lower()
    if s in ('white', 'black'):
        return NAMED[s]
    if s.startswith('#'):
        h = s[1:]
        if len(h) in (3, 4):
            h = ''.join(c * 2 for c in h)
        r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1
        return (r, g, b, a)
    m = re.match(r'rgba?\(\s*([\d.]+%?)[\s,]+([\d.]+%?)[\s,]+([\d.]+%?)(?:\s*[,/]\s*([\d.]+%?))?\s*\)', s)
    if not m:
        return None
    def ch(v):
        return float(v[:-1]) * 2.55 if v.endswith('%') else float(v)
    a = m.group(4)
    a = (float(a[:-1]) / 100 if a and a.endswith('%') else float(a)) if a else 1
    return (ch(m.group(1)), ch(m.group(2)), ch(m.group(3)), a)


def fmt(r, g, b, a):
    r, g, b = [max(0, min(255, round(x))) for x in (r, g, b)]
    return '#%02x%02x%02x' % (r, g, b) if a >= 0.999 else 'rgb(%d %d %d / %d%%)' % (r, g, b, round(a * 100))


def remap(c, kind):
    r, g, b, a = c
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if kind == 'bg':
        if a < 0.999 and l > 0.85:      # translucent white overlays (glass) -> translucent light-on-dark
            return fmt(255, 255, 255, min(a, 0.08) if a > 0.3 else a * 0.25)
        if l <= 0.6:
            return None                 # already dark / saturated brand fill: keep
        nl, ns = 0.10 + (1 - l) * 0.8, s * (0.55 if s > 0.15 else 1)
    elif kind == 'border':
        if l <= 0.6:
            return None
        nl, ns = 0.22 + (1 - l) * 0.55, s * 0.5
    else:  # text
        if l >= 0.5:
            return None                 # light text (on brand fills) stays
        nl, ns = (0.90 - l * 0.55) if s < 0.35 else max(0.68, 1 - l), min(1, s * 1.05)
    rr, gg, bb = colorsys.hls_to_rgb(h, nl, ns)
    return fmt(rr * 255, gg * 255, bb * 255, a)


TOKENS = {}


def collect_tokens(rules):
    for pre, body in rules:
        if isinstance(body, list):
            collect_tokens(body)
            continue
        for p, v in decls(body):
            if p.startswith('--'):
                TOKENS[p] = v


def resolve_var(val, kind):
    """`color: var(--navy)` where --navy is a kept brand token: write the remapped literal for this use only."""
    m = re.fullmatch(r'\s*var\((--[\w-]+)(?:\s*,\s*([^)]+))?\)\s*(!important)?\s*', val)
    if not m:
        return None
    src = TOKENS.get(m.group(1)) or m.group(2) or ''
    if kind_of(m.group(1)):  # token is remapped where it is defined
        return None
    lit = COLOR_RE.fullmatch(src.strip())
    if not lit:
        return None
    c = parse_color(lit.group(0))
    n = remap(c, kind) if c else None
    return (n + (' !important' if m.group(3) else '')) if n else None


def convert_value(val, kind):
    if 'var(' in val and not COLOR_RE.search(val):
        return resolve_var(val, kind)
    changed = [False]
    def sub(m):
        c = parse_color(m.group(0))
        if not c:
            return m.group(0)
        n = remap(c, kind)
        if n is None:
            return m.group(0)
        changed[0] = True
        return n
    out = COLOR_RE.sub(sub, val)
    return out if changed[0] else None


def kind_of(prop, value=''):
    p = prop.lower()
    if p.startswith('--'):
        if BG_TOKEN.search(p):
            return 'border' if re.search(r'line|border', p) else 'bg'
        if TEXT_TOKEN.search(p):
            return 'text'
        return None
    if p in ('background', 'background-color', 'background-image'):
        return 'bg'
    if p.startswith('border') or p in ('outline', 'outline-color', 'column-rule', 'text-decoration-color'):
        return 'border'
    if p in ('color', 'fill', 'stroke', 'caret-color', '-webkit-text-fill-color'):
        return 'text'
    return None


def strip_comments(css):
    return re.sub(r'/\*.*?\*/', '', css, flags=re.S)


def parse(css):
    """Yield (prelude, body) pairs; nested at-rules return a list body."""
    i, n, out = 0, len(css), []
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        pre = css[i:j].strip()
        semi = pre.rfind(';')  # @import / @charset statements before a rule
        if semi >= 0:
            pre = pre[semi + 1:].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == '{':
                depth += 1
            elif css[k] == '}':
                depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if pre.startswith('@media') or pre.startswith('@supports') or pre.startswith('@container') or pre.startswith('@layer'):
            out.append((pre, parse(body)))
        elif not pre.startswith('@'):
            out.append((pre, body))
        i = k
    return out


def scope_selectors(pre):
    sels = []
    for s in re.split(r',(?![^(]*\))', pre):
        s = s.strip()
        if not s or re.match(r'^(html|body|:root|:host)\b', s) or 'data-theme' in s or 'prefers-color' in s:
            continue
        for sc in SCOPES:
            sels.append(sc + ' ' + s)
    return sels


def decls(body):
    for d in re.split(r';(?![^(]*\))', body):
        if ':' not in d:
            continue
        p, v = d.split(':', 1)
        yield p.strip(), v.strip()


def emit(rules):
    out = []
    for pre, body in rules:
        if isinstance(body, list):
            inner = emit(body)
            if inner:
                out.append(pre + ' { ' + ' '.join(inner) + ' }')
            continue
        conv = []
        for p, v in decls(body):
            k = kind_of(p)
            if not k:
                continue
            nv = convert_value(v, k)
            if nv:
                conv.append(p + ': ' + nv)
        sels = scope_selectors(pre)
        if conv and sels:
            out.append(', '.join(sels) + ' { ' + '; '.join(conv) + '; }')
    return out


def shell_reassert(c):
    """Re-state the shell header / tab / bar rules inside the dark scope so converted page rules cannot override them."""
    sys.path.insert(0, str(pathlib.Path(__file__).parent))
    import apply_shell
    out = []
    for line in apply_shell.block(c).splitlines():
        if line.startswith('/*') or line.startswith('@') or '{' not in line or 'dms-paper' in line or 'dms-ink' in line or '--dms-navy:' in line:
            continue
        sel, body = line.split('{', 1)
        sels = [s.strip() for s in re.split(r',(?![^(]*\))', sel) if s.strip()]
        out.append(', '.join(sc + ' ' + s for s in sels for sc in SCOPES) + ' {' + body)
    return out


def shell_dark(c):
    """Dark variant of the generated shell filter card (header / tabs are already dark)."""
    out = shell_reassert(c)
    if not c.get('filters'):
        return out
    r, f = c['root'], c['filters']
    fld = ', '.join(c.get('field', ['label']) + [x + ' > :is(label, span)' for x in c.get('field', ['label'])])
    for sc in SCOPES:
        out.append(sc + ' ' + r + ' ' + f + ' { background: #18202b !important; color: #e7ecf3; border-color: #2e3a49 !important; }')
        out.append(sc + ' ' + r + ' ' + f + ' :is(select, input:not([type=checkbox]):not([type=radio])) { background: #1e2834 !important; color: #e7ecf3 !important; border-color: #2e3a49 !important; }')
        out.append(sc + ' ' + r + ' ' + f + ' :is(' + fld + ') { color: #b3bfce !important; }')
    return out


def build(name, c, css):
    base = re.sub(r'\n?/\* ==== DM [^*]*?v1 · generated.*?/\* ==== end DM [^*]*? v1 ==== \*/\n?', '\n', css, flags=re.S)
    parsed = parse(strip_comments(base.replace('<style>', '').replace('</style>', '')))
    TOKENS.clear()
    collect_tokens(parsed)
    rules = emit(parsed)
    root_bg = []
    for sc in SCOPES:
        root_bg.append(sc + ' ' + c['root'] + ' { color-scheme: dark; }')
    return BEGIN + '\n' + '\n'.join(root_bg + rules + shell_dark(c)) + '\n' + END + '\n'


def strip_block(text, b, e):
    return re.sub(r'\n?' + re.escape(b) + r'.*?' + re.escape(e) + r'\n?', '\n', text, flags=re.S)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ''
    stale = []
    for name in CFG.get('_dark', []):
        c = CFG[name]
        d = ROOT / name
        jsf = d / 'dashboard.js'
        js = jsf.read_text(encoding='utf-8')
        if c.get('inject_before'):  # stylesheet lives inside the JS
            m = re.search(r'const CSS = `(.*?)' + re.escape(c['inject_before']), js, flags=re.S)
            css_src, target, text = m.group(1), jsf, js
        else:
            target = d / 'dashboard.css'
            text = target.read_text(encoding='utf-8')
            css_src = text
        clean = strip_block(text, BEGIN, END)
        if mode == '--remove':
            new_css = clean.rstrip() + '\n'
        elif BEGIN in text:  # refresh in place so the shell block keeps its position
            blk = build(name, c, css_src)
            new_css = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', lambda m: blk, text, count=1, flags=re.S)
        else:
            blk = build(name, c, css_src)
            if c.get('inject_before'):
                i = clean.index(c['inject_before'])
                new_css = clean[:i] + blk + clean[i:]
            else:
                new_css = clean.rstrip() + '\n\n' + blk
        js_text = new_css if target == jsf else js
        if JS_BEGIN in js_text and mode != '--remove':
            new_js = re.sub(re.escape(JS_BEGIN) + r'.*?' + re.escape(JS_END) + r'\n?', lambda m: SYNC, js_text, count=1, flags=re.S)
        else:
            js_clean = strip_block(js_text, JS_BEGIN, JS_END).rstrip() + '\n'
            new_js = js_clean if mode == '--remove' else js_clean + '\n' + SYNC
        if mode == '--check':
            if (target != jsf and new_css != text) or new_js != js:
                stale.append(name)
            continue
        if target != jsf and new_css != text:
            target.write_text(new_css, encoding='utf-8')
        if new_js != js:
            jsf.write_text(new_js, encoding='utf-8')
        print(('removed ' if mode == '--remove' else 'dark theme ') + name)
    if mode == '--check':
        print('dark theme stale or missing: ' + (', '.join(stale) if stale else 'none'))
        sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
