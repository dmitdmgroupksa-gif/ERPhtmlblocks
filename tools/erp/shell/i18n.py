"""Add an English / العربية language button to dashboards that have none (listed under "_i18n" in shell_map.json).

Appends a generated script to each dashboard.js that:
  * inserts a Language button into the dashboard header (styled by the shell like the other header buttons),
  * translates interface text (text nodes, placeholder/title/aria-label) from i18n_ar.json after every render,
  * sets dir="rtl" on the dashboard root, and remembers the choice per viewer (localStorage key "dms-lang", shared by all
    these dashboards). ERP data values are shown as recorded.
Only dictionary entries that occur in that dashboard's source are embedded. Re-run to refresh; --remove / --check.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).parent
CFG = json.loads((HERE / 'shell_map.json').read_text(encoding='utf-8'))
AR = json.loads((HERE / 'i18n_ar.json').read_text(encoding='utf-8'))
BEGIN = '/* ==== DM language v1 · generated by tools/erp/shell/i18n.py ==== */'
END = '/* ==== end DM language v1 ==== */'

RUNTIME = r'''
;(function () {
  var root = typeof root_element !== 'undefined' ? root_element : document;
  var AR = __DICT__, SEL = __SEL__, SLOT = __SLOT__, KEY = 'dms-lang', ATTRS = ['placeholder', 'title', 'aria-label'];
  var lang = 'en'; try { lang = localStorage.getItem(KEY) === 'ar' ? 'ar' : 'en'; } catch (e) { /* storage blocked */ }
  var orig = new WeakMap(), busy = false, timer = 0;
  function host() { return root.querySelector(SEL); }
  function has(k) { return !!k && Object.prototype.hasOwnProperty.call(AR, k); }
  function text(h) {
    var w = document.createTreeWalker(h, NodeFilter.SHOW_TEXT), n;
    while ((n = w.nextNode())) {
      var p = n.parentElement; if (!p || /^(SCRIPT|STYLE|TEXTAREA|CODE|PRE)$/.test(p.tagName) || p.closest('.dms-lang-btn')) continue;
      if (lang === 'ar') { var t = n.nodeValue.trim(), m = t.match(/^([^A-Za-z0-9(]*)(.*?)([\s:.…·-]*)$/), k = has(t) ? t : (m && has(m[2]) ? m[2] : '');
        if (k) { if (!orig.has(n)) orig.set(n, n.nodeValue); n.nodeValue = n.nodeValue.replace(k, AR[k]); } }
      else if (orig.has(n)) { n.nodeValue = orig.get(n); orig.delete(n); }
    }
    h.querySelectorAll('[placeholder],[title],[aria-label]').forEach(function (e) {
      ATTRS.forEach(function (a) {
        var v = e.getAttribute(a), k = 'data-dms-' + a; if (v == null) return;
        if (lang === 'ar') { var t = v.trim(); if (Object.prototype.hasOwnProperty.call(AR, t)) { if (!e.hasAttribute(k)) e.setAttribute(k, v); e.setAttribute(a, AR[t]); } }
        else if (e.hasAttribute(k)) { e.setAttribute(a, e.getAttribute(k)); e.removeAttribute(k); }
      });
    });
  }
  function button(h) {
    var slot = SLOT === '&' ? h : h.querySelector(SLOT); if (!slot) return;
    var b = slot.querySelector('.dms-lang-btn');
    if (!b) {
      b = document.createElement('button'); b.type = 'button'; b.className = 'dms-lang-btn';
      b.addEventListener('click', function () { lang = lang === 'ar' ? 'en' : 'ar'; try { localStorage.setItem(KEY, lang); } catch (e) { /* optional */ } apply(); });
      var first = slot.querySelector(':scope > button, :scope > a, :scope > div > button'); first ? first.parentNode.insertBefore(b, first) : slot.appendChild(b);
    }
    b.textContent = lang === 'ar' ? 'English' : 'العربية'; b.setAttribute('aria-label', lang === 'ar' ? 'Switch to English' : 'التبديل إلى العربية'); b.lang = lang === 'ar' ? 'en' : 'ar';
  }
  function apply() {
    var h = host(); if (!h) return;
    busy = true;
    try { button(h); text(h); h.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr'); h.setAttribute('lang', lang); } finally { mo.takeRecords(); busy = false; }
  }
  var mo = new MutationObserver(function () { if (busy) return; clearTimeout(timer); timer = setTimeout(apply, 25); });
  mo.observe(root === document ? (document.body || document.documentElement) : root, { childList: true, subtree: true, characterData: false });
  apply();
})();
'''


def snippet(name, c):
    d = ROOT / name
    src = (d / 'dashboard.js').read_text(encoding='utf-8')
    src = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), '', src, flags=re.S)
    if (d / 'dashboard.html').exists():
        src += (d / 'dashboard.html').read_text(encoding='utf-8')
    def variants(k):
        e = k.replace('&', '&amp;').replace("'", '&#39;')
        x = e.replace('·', '&middot;').replace('—', '&mdash;')
        return [k, e, x, k.replace('·', '&middot;').replace('—', '&mdash;')]
    used = {k: v for k, v in AR.items() if any(x in src for x in variants(k))}
    js = (RUNTIME.replace('__DICT__', json.dumps(used, ensure_ascii=False, sort_keys=True))
          .replace('__SEL__', json.dumps(c['root'])).replace('__SLOT__', json.dumps(CFG['_i18n'][name])))
    return BEGIN + js + END + '\n', len(used)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ''
    stale = []
    for name in CFG.get('_i18n', {}):
        f = ROOT / name / 'dashboard.js'
        text = f.read_text(encoding='utf-8')
        if mode == '--remove':
            new = re.sub(r'\n?' + re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '\n', text, flags=re.S)
        else:
            blk, n = snippet(name, CFG[name])
            if BEGIN in text:
                new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', lambda m: blk, text, count=1, flags=re.S)
            else:
                new = text.rstrip() + '\n\n' + blk
        if mode == '--check':
            if new != text:
                stale.append(name)
            continue
        if new != text:
            f.write_text(new, encoding='utf-8')
        print(('removed ' if mode == '--remove' else 'language ') + name + ('' if mode == '--remove' else ' (' + str(n) + ' strings)'))
    if mode == '--check':
        print('language stale or missing: ' + (', '.join(stale) if stale else 'none'))
        sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
