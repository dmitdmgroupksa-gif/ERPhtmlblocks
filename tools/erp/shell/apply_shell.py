"""Apply the DM dashboard shell standard (shared/Dashboard Shell/README.md) to every dashboard.

For each entry in shell_map.json this writes one generated CSS block, between the markers below, at the end of the
dashboard's stylesheet (or inside a JS-injected <style> when the dashboard has no CSS file). It restyles the existing
header, tab bar and filter bar elements only; no data code changes. Re-running replaces the block; --remove deletes it.

    python tools/erp/shell/apply_shell.py            # apply / refresh all
    python tools/erp/shell/apply_shell.py --check    # exit 1 if any block is missing or stale
    python tools/erp/shell/apply_shell.py --remove   # roll back
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
MAP = json.loads((pathlib.Path(__file__).parent / 'shell_map.json').read_text(encoding='utf-8'))
BEGIN = '/* ==== DM shell standard v1 · generated by tools/erp/shell/apply_shell.py · do not edit by hand ==== */'
END = '/* ==== end DM shell standard v1 ==== */'


def doubled(sel):
    """Raise specificity without changing what matches: #a -> #a#a, .a -> .a.a."""
    m = re.match(r'^([#.][\w-]+)', sel)
    return m.group(1) + sel if m else sel


def under(r, scope, items):
    items = items if isinstance(items, list) else [items]
    return ', '.join(r + ' ' + scope + (' ' + i if i else '') for i in items)


def block(c):
    r = doubled(c['root'])
    out = [BEGIN, r + ' { --dms-navy: #0f2147; --dms-navy2: #1a3263; --dms-royal: #2b4fc1; --dms-royal-ink: #1d3a9f; --dms-line: #d8dee7; '
           '--dms-paper: #fff; --dms-paper2: #f6f8fb; --dms-ink: #16202e; --dms-ink2: #47556a; }']
    for w in c.get('contents', []):  # wrappers whose children should behave as direct children (for reordering)
        out.append(r + ' ' + w + ' { display: contents; }')
    for w in c.get('plain', []):  # wrappers that used to paint a band behind header + filters
        out.append(r + ' ' + w + ' { background: none; border: 0; box-shadow: none; padding: 0; margin: 0; border-radius: 0; color: inherit; }')
    h = c.get('header')
    if h:
        out.append(r + ' ' + h + ' { display: flex; align-items: center; justify-content: space-between; flex-wrap: wrap; gap: 12px 16px; '
                   'background: linear-gradient(120deg, var(--dms-navy), var(--dms-navy2)); color: #fff; border: 0; border-radius: 14px; '
                   'padding: 16px 20px; margin: 0 0 12px; box-shadow: 0 8px 22px -16px rgb(15 33 71 / 70%); min-height: 0; }')
        out.append(under(r, h, ['h1', 'h2', 'h3'] + c.get('title', [])) + ' { color: #fff; font-size: 21px; line-height: 1.25; font-weight: 700; '
                   'letter-spacing: 0; text-transform: none; margin: 0; }')
        out.append(under(r, h, ['p'] + c.get('sub', [])) + ' { color: rgb(255 255 255 / 78%); font-size: 12.5px; margin: 2px 0 0; opacity: 1; }')
        out.append(under(r, h, c.get('eyebrow', [])) + ' { color: rgb(255 255 255 / 70%); font-size: 11px; letter-spacing: .08em; text-transform: uppercase; font-weight: 600; }' if c.get('eyebrow') else '')
        btn = c.get('hbtn', 'button')
        btn = (btn if isinstance(btn, list) else [btn]) + ['.dms-lang-btn']
        out.append(under(r, h, btn) + ' { min-height: 34px; padding: 0 13px; border-radius: 8px; border: 1px solid rgb(255 255 255 / 30%); '
                   'background: rgb(255 255 255 / 10%); color: #fff; font-weight: 500; font-size: 13px; box-shadow: none; text-shadow: none; }')
        out.append(under(r, h, [b + ':hover' for b in (btn if isinstance(btn, list) else [btn])]) + ' { background: rgb(255 255 255 / 18%); color: #fff; }')
        if c.get('hprimary'):
            out.append(under(r, h, c['hprimary']) + ' { background: #fff; color: var(--dms-navy); border-color: #fff; font-weight: 600; }')
        if c.get('lang'):
            out.append(under(r, h, c['lang']) + ' { display: inline-flex; gap: 2px; padding: 2px; border: 1px solid rgb(255 255 255 / 30%); border-radius: 8px; background: rgb(255 255 255 / 10%); }')
            out.append(under(r, h, [l + ' button' for l in c['lang']]) + ' { min-height: 28px; padding: 0 10px; border: 0; border-radius: 6px; background: transparent; color: #fff; }')
            out.append(under(r, h, [l + ' ' + c.get('langon', '.on') for l in c['lang']]) + ' { background: #fff; color: var(--dms-navy); font-weight: 600; }')
        for x in c.get('hextra', []):
            out.append(r + ' ' + h + ' ' + x)
    t = c.get('tabs')
    if t:
        dark_bg = c.get('tabs_in_header')
        out.append(r + ' ' + t + ' { display: flex; flex-wrap: nowrap; align-items: center; gap: 4px; overflow-x: auto; scrollbar-width: thin; '
                   'background: ' + ('rgb(255 255 255 / 10%)' if dark_bg else 'var(--dms-royal)') + '; border: 0; border-radius: 12px; padding: 5px; '
                   + ('margin: 0;' if dark_bg else 'margin: 0 0 12px; box-shadow: 0 10px 24px -14px rgb(20 40 130 / 70%);') + ' min-height: 0; }')
        tab = c.get('tab', 'button')
        out.append(under(r, t, tab) + ' { flex: 0 0 auto; display: inline-flex; align-items: center; gap: 6px; white-space: nowrap; background: transparent; '
                   'color: rgb(255 255 255 / 90%); border: 0; border-radius: 8px; padding: 8px 14px; min-height: 36px; margin: 0; font-weight: 500; '
                   'font-size: 13px; box-shadow: none; text-decoration: none; cursor: pointer; }')
        out.append(under(r, t, [x + ':hover' for x in (tab if isinstance(tab, list) else [tab])]) + ' { background: rgb(255 255 255 / 16%); color: #fff; }')
        out.append(under(r, t, c.get('active', [tab + '.on'])) + ' { background: #fff; color: var(--dms-royal-ink); font-weight: 600; '
                   'box-shadow: 0 4px 12px -6px rgb(10 25 90 / 60%); border: 0; }')
        for x in c.get('textra', []):
            out.append(r + ' ' + t + ' ' + x)
    b = c.get('bar')  # a top strip that holds tabs + a few buttons (no title): royal bar, buttons as white ghosts
    if b:
        out.append(r + ' ' + b + ' { background: var(--dms-royal); border: 0; border-radius: 14px; padding: 5px 8px; margin: 0 0 12px; '
                   'box-shadow: 0 10px 24px -14px rgb(20 40 130 / 70%); display: flex; align-items: center; justify-content: space-between; gap: 8px; flex-wrap: wrap; }')
        out.append(under(r, b, c.get('barbtn', [])) + ' { min-height: 32px; border-radius: 8px; border: 1px solid rgb(255 255 255 / 35%); background: rgb(255 255 255 / 12%); color: #fff; box-shadow: none; }' if c.get('barbtn') else '')
        out.append(under(r, b, c.get('barlabel', [])) + ' { color: rgb(255 255 255 / 90%); }' if c.get('barlabel') else '')
    f = c.get('filters')
    if f:
        out.append(r + ' ' + f + ' { background: var(--dms-paper); color: var(--dms-ink); border: 1px solid var(--dms-line); border-radius: 12px; '
                   'padding: 12px 14px; margin: 0 0 12px; box-shadow: 0 1px 2px rgb(16 24 40 / 6%), 0 4px 14px -6px rgb(16 24 40 / 12%); }')
        if c.get('grid', True):
            g = c.get('gridel', f)
            out.append(r + ' ' + g + ' { display: grid; grid-template-columns: repeat(auto-fit, minmax(150px, 1fr)); gap: 10px 12px; align-items: end; }')
        fld = c.get('field', ['label'])
        out.append(under(r, f, fld) + ' { display: grid; gap: 4px; align-content: end; min-width: 0; margin: 0; color: var(--dms-ink2); font-size: 12px; '
                   'font-weight: 500; letter-spacing: 0; text-transform: none; max-width: none; }')
        out.append(under(r, f, [x + ' > span' for x in fld]) + ' { color: inherit; font-size: inherit; }')
        out.append(under(r, f, [x + ' > label' for x in fld if x != 'label']) + ' { color: var(--dms-ink2); font-size: 12px; font-weight: 500; letter-spacing: 0; text-transform: none; margin: 0; }'
                   if [x for x in fld if x != 'label'] else '')
        out.append(under(r, f, ['select', 'input:not([type=checkbox]):not([type=radio])']) + ' { width: 100%; height: 38px; min-height: 38px; padding: 0 10px; '
                   'border: 1px solid var(--dms-line); border-radius: 8px; background: var(--dms-paper2); color: var(--dms-ink); font-size: 13px; box-sizing: border-box; box-shadow: none; }')
        out.append(under(r, f, c.get('fbtn', ['button'])) + ' { min-height: 38px; border-radius: 8px; align-self: end; }')
        if c.get('fprimary'):
            out.append(under(r, f, c['fprimary']) + ' { background: var(--dms-royal); border-color: var(--dms-royal); color: #fff; }')
        for x in c.get('fullrow', []):
            out.append(r + ' ' + f + ' ' + x + ' { grid-column: 1 / -1; }')
        for x in c.get('fextra', []):
            out.append(r + ' ' + f + ' ' + x)
        if c.get('dark'):
            d = c['dark']
            out.append(d + ' ' + f + ' { background: #18202b; color: #e7ecf3; border-color: #2e3a49; }')
            out.append(d + ' ' + f + ' :is(select, input:not([type=checkbox]):not([type=radio])) { background: #1e2834; color: #e7ecf3; border-color: #2e3a49; }')
            out.append(d + ' ' + f + ' :is(' + ', '.join(fld) + ') { color: #b3bfce; }')
    o = c.get('order')  # Fleet order: header -> tabs -> filters, when they are siblings of this parent
    if o:
        out.append(r + ' ' + o + ' { display: flex; flex-direction: column; }' if o != '&' else r + ' { display: flex; flex-direction: column; }')
        par = r + (' ' + o if o != '&' else '')
        out.append(', '.join([par + ' > *'] + [r + ' ' + w + ' > *' for w in c.get('contents', [])]) + ' { order: 5; }')
        for i, k in enumerate(['header', 'bar', 'tabs', 'filters']):
            sel = c.get('order_' + k, c.get(k))
            if sel:
                out.append(r + ' ' + sel + ' { order: ' + str(i + 1) + ' !important; }')
    out.append('@media (max-width: 760px) { ' + ((r + ' ' + h + ' { padding: 14px 16px; } ') if h else '') +
               ((r + ' ' + c.get('gridel', f) + ' { grid-template-columns: repeat(2, minmax(0, 1fr)); } ') if (f and c.get('grid', True)) else '') +
               ((r + ' ' + t + ' { flex-wrap: nowrap; } ') if t else '') + '}')
    for x in c.get('extra', []):
        out.append(r + ' ' + x)
    out.append(END)
    return '\n'.join(x for x in out if x) + '\n'


def strip(text):
    return re.sub(r'\n?' + re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '\n', text, flags=re.S).rstrip() + '\n'


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ''
    stale = []
    for name, c in MAP.items():
        if name.startswith('_'):
            continue
        d = ROOT / name
        target = d / c.get('file', 'dashboard.css')
        text = target.read_text(encoding='utf-8')
        new_block = '' if mode == '--remove' else block(c)
        if BEGIN in text and mode != '--remove':  # refresh in place so other generated blocks keep their position
            new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', lambda m: new_block, text, count=1, flags=re.S)
        elif c.get('inject_before'):  # CSS lives in a JS string: insert before the given marker (e.g. the closing </style>)
            base = strip(text) if BEGIN in text else text
            marker = c['inject_before']
            assert base.count(marker) >= 1, name + ': marker not found'
            i = base.index(marker)
            new = base if mode == '--remove' else base[:i] + new_block + base[i:]
            new = new if new.endswith('\n') else new + '\n'
        else:
            new = strip(text) + ('\n' + new_block if new_block else '')
        if mode == '--check':
            if new != text:
                stale.append(name)
            continue
        if new != text:
            target.write_text(new, encoding='utf-8')
            print(('removed ' if mode == '--remove' else 'applied ') + name)
    if mode == '--check':
        print('stale or missing: ' + (', '.join(stale) if stale else 'none'))
        sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
